import re

INPUT_FILE = r"C:\Users\dejid\Desktop\karaoke_pipeline\work\corpus\audio.txt"
OUTPUT_FILE = INPUT_FILE

# =====================================================
# LOAD
# =====================================================

with open(INPUT_FILE, "r", encoding="utf-8") as f:
    text = f.read()

# =====================================================
# REMOVE UTF BOM
# =====================================================

text = text.replace("\ufeff", "")

# =====================================================
# REMOVE SRT BLOCK NUMBERS
# =====================================================

# 1
# 2
# 3

text = re.sub(
    r"^\d+\s*$",
    "",
    text,
    flags=re.MULTILINE
)

# =====================================================
# REMOVE WHISPER / SRT TIMESTAMPS
# =====================================================

# [00:00.000 --> 00:01.000]
# 00:00:00,000 --> 00:00:01,000

text = re.sub(
    r"\[\d{2}:\d{2}(?::\d{2})?\.\d+\s*-->\s*\d{2}:\d{2}(?::\d{2})?\.\d+\]",
    " ",
    text
)

text = re.sub(
    r"\d{2}:\d{2}:\d{2},\d+\s*-->\s*\d{2}:\d{2}:\d{2},\d+",
    " ",
    text
)

# =====================================================
# REMOVE ASS TAGS
# =====================================================

# {\k55}
# {\fad(100,100)}
# etc

text = re.sub(
    r"\{.*?\}",
    "",
    text
)

# =====================================================
# REMOVE HTML TAGS
# =====================================================

text = re.sub(
    r"<.*?>",
    "",
    text
)

# =====================================================
# LOWERCASE
# =====================================================

text = text.lower()

# =====================================================
# KEEP UNICODE LETTERS / DIGITS / SPACES / APOSTROPHES
# =====================================================

text = re.sub(
    r"[^\w\s']",
    " ",
    text,
    flags=re.UNICODE
)

text = text.replace("_", " ")

# =====================================================
# REMOVE EXTRA SPACES
# =====================================================

text = re.sub(r"\s+", " ", text)

text = text.strip()

# =====================================================
# SAVE
# =====================================================

with open(OUTPUT_FILE, "w", encoding="utf-8") as f:
    f.write(text)

print("DONE ->", OUTPUT_FILE)